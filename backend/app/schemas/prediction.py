from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

class PredictRequest(BaseModel):
    city: str = Field(..., description="Indian metropolitan city, e.g. Bangalore, Mumbai, Pune")
    property_type: str = Field(..., description="Apartment, Independent House, or Villa")
    bhk: int = Field(..., ge=1, le=10, description="Bedrooms count (1 to 10)")
    bathrooms: int = Field(..., ge=1, le=10, description="Bathrooms count (1 to 10)")
    area_sqft: float = Field(..., ge=150.0, le=15000.0, description="Total area in square feet")
    balcony: int = Field(default=1, ge=0, le=1, description="1 if balcony present, else 0")
    locality: Optional[str] = Field(default=None, description="Locality within the city")

class ShapContribution(BaseModel):
    feature: str
    display_name: str
    shap_lakhs: float
    shap_inr: float
    effect: str

class ShapExplanationResponse(BaseModel):
    baseline_lakhs: float
    baseline_inr: float
    predicted_lakhs: float
    predicted_inr: float
    sum_shap_lakhs: float
    is_additive: bool
    feature_contributions: List[ShapContribution]
    positive_contributions: List[ShapContribution]
    negative_contributions: List[ShapContribution]
    top_drivers: List[ShapContribution]

class PredictResponse(BaseModel):
    predicted_price_lakhs: float
    predicted_price_inr: float
    formatted_price: str
    model_name: str
    model_type: str
    input_features: Dict[str, Any]
    explanation: Optional[ShapExplanationResponse] = None
    prediction_interval: Optional[Dict[str, str]] = None
    disclaimer: str = (
        "This price is an algorithmic statistical estimate generated by Machine Learning "
        "trained on Indian metropolitan residential market listings. Actual transaction prices "
        "may vary depending on builder reputation, micro-locality infrastructure, and exact physical condition."
    )
